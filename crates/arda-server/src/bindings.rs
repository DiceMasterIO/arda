/// Workspace-relative directory of the committed bindings.
pub const BINDINGS_DIR: &str = "bindings/ts/arda";

/// The committed directory, resolved from this crate's manifest.
#[must_use]
pub fn bindings_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join(BINDINGS_DIR)
}

fn one<T: TS + 'static>(cfg: &ts_rs::Config) -> ServerResult<(String, String)> {
    let text =
        T::export_to_string(cfg).map_err(|e| ServerError::Internal(format!("ts-rs: {e}")))?;
    Ok((format!("{}.ts", T::ident(cfg)), text))
}

macro_rules! exported {
    ($($t:ty),* $(,)?) => {
        /// Every exported file as `(file name, contents)`, sorted by name, plus `index.ts`.
        ///
        /// # Errors
        /// [`ServerError::Internal`] if ts-rs cannot render a type.
        pub fn render() -> ServerResult<Vec<(String, String)>> {
            let cfg = ts_rs::Config::new();
            let mut files = vec![$( one::<$t>(&cfg)? ),*];
            files.sort();
            let mut index = String::from(
                "// Generated by arda-server (src/bindings.rs). Do not edit by hand.\n\n",
            );
            index.push_str(&format!("export const CONTRACT_VERSION = {CONTRACT_VERSION};\n"));
            index.push_str(&format!("export const API_VERSION = \"{API_VERSION}\";\n\n"));
            for (name, _) in &files {
                let stem = name.trim_end_matches(".ts");
                index.push_str(&format!("export type {{ {stem} }} from \"./{stem}\";\n"));
            }
            files.push(("index.ts".to_owned(), index));
            Ok(files)
        }
    };
}

