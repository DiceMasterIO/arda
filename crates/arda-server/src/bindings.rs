#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn committed_bindings_are_fresh() {
        let dir = bindings_dir();
        let files = render().unwrap();
        if std::env::var_os("ARDA_BLESS_BINDINGS").is_some() {
            std::fs::create_dir_all(&dir).unwrap();
            for entry in std::fs::read_dir(&dir).unwrap() {
                std::fs::remove_file(entry.unwrap().path()).unwrap();
            }
            for (name, text) in &files {
                std::fs::write(dir.join(name), text).unwrap();
            }
        }
        let mut on_disk: Vec<String> = std::fs::read_dir(&dir)
            .unwrap_or_else(|e| panic!("{}: {e}; bless with ARDA_BLESS_BINDINGS=1", dir.display()))
            .map(|e| e.unwrap().file_name().to_string_lossy().into_owned())
            .collect();
        on_disk.sort();
        let mut expected: Vec<String> = files.iter().map(|(n, _)| n.clone()).collect();
        expected.sort();
        assert_eq!(
            on_disk, expected,
            "stale file set; rerun with ARDA_BLESS_BINDINGS=1"
        );
        for (name, text) in &files {
            let committed = std::fs::read_to_string(dir.join(name)).unwrap();
            assert_eq!(
                &committed, text,
                "{name} is stale; rerun with ARDA_BLESS_BINDINGS=1"
            );
        }
    }

    #[test]
    fn u64_ids_are_strings_not_bigints() {
        let files = render().unwrap();
        assert!(files.iter().all(|(_, text)| !text.contains("bigint")));
        let cell = &files.iter().find(|(n, _)| n == "CellSample.ts").unwrap().1;
        assert!(cell.contains("fine: FineHeights | null"), "{cell}");
    }

    #[test]
    fn npc_types_are_exported_with_string_ids() {
        let files = render().unwrap();
        let text = |name: &str| {
            files
                .iter()
                .find(|(n, _)| n == name)
                .map(|(_, t)| t.clone())
                .unwrap_or_else(|| panic!("{name} is not exported"))
        };
        for name in [
            "Npc.ts",
            "Sheet.ts",
            "Population.ts",
            "SettlementProfile.ts",
            "BuildingSpec.ts",
        ] {
            text(name);
        }
        assert!(text("NpcId.ts").contains("export type NpcId = string;"));
        assert!(text("Npc.ts").contains("id: NpcId"));
        assert!(text("SettlementProfile.ts").contains("id: string"));
        assert!(text("BuildingSpec.ts").contains("tags?: Array<string>"));
        let index = text("index.ts");
        assert!(
            index.contains("export type { Npc } from \"./Npc\";"),
            "{index}"
        );
    }

    #[test]
    fn tactical_layout_binding_describes_the_layout_json() {
        let files = render().unwrap();
        let find = |n: &str| &files.iter().find(|(f, _)| f == n).unwrap().1;
        let layout = find("TacticalLayoutDto.ts");
        assert!(layout.contains("squares: Array<SquareDto>"), "{layout}");
        let asset = find("AssetRefDto.ts");
        assert!(
            asset.contains("\"id\": string") && asset.contains("\"query\""),
            "{asset}"
        );
        assert!(find("NotYetError.ts").contains("planned_source: string"));
    }
}
